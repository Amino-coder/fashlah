/** Two distinct random picks from an array — used for both bot names and
 *  bot responses, anywhere "two different computer players" need two
 *  different values. */
export function pickTwoDistinct<T>(pool: T[]): [T, T] {
  const i = Math.floor(Math.random() * pool.length);
  let j = Math.floor(Math.random() * (pool.length - 1));
  if (j >= i) j++;
  return [pool[i], pool[j]];
}

export function pickOne<T>(pool: T[]): T {
  return pool[Math.floor(Math.random() * pool.length)];
}

